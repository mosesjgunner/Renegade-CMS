export type ProductionInstallInput = {
  appUrl: string
  proxyMode: string
  trustedProxyHops: string
  profile: string
  webBind: string
  ownerEmail?: string
}

export class ProductionInstallError extends Error {
  constructor(readonly fields: string[]) {
    super(`Unsafe production installation configuration: ${fields.join(', ')}`)
    this.name = 'ProductionInstallError'
  }
}

export function validateProductionInstallInput(input: ProductionInstallInput): void {
  const invalid: string[] = []
  try {
    const url = new URL(input.appUrl)
    if (url.protocol !== 'https:' || url.pathname !== '/' || url.search || url.hash)
      invalid.push('APP_URL')
    if (['localhost', '127.0.0.1', '[::1]'].includes(url.hostname)) invalid.push('APP_URL')
  } catch {
    invalid.push('APP_URL')
  }
  if (!['direct', 'trusted'].includes(input.proxyMode)) invalid.push('PROXY_MODE')
  if (!['1', '2', '3'].includes(input.trustedProxyHops)) invalid.push('TRUSTED_PROXY_HOPS')
  if (!['Lean', 'Standard'].includes(input.profile)) invalid.push('DEPLOYMENT_PROFILE')
  if (!/^(127\.0\.0\.1:\d{1,5}|\[::1\]:\d{1,5})$/.test(input.webBind))
    invalid.push('RENEGADE_WEB_BIND')
  if (input.ownerEmail && !/^[^\s@]+@[^\s@]+\.[^\s@]+$/.test(input.ownerEmail))
    invalid.push('OWNER_EMAIL')
  if (invalid.length) throw new ProductionInstallError([...new Set(invalid)].sort())
}

export function hasInstallerManagedConfig(content: string): boolean {
  return /^# Renegade CMS production configuration \(generated by install\.sh\)$/m.test(content)
}

export function hasUnsafeProductionConfig(content: string): boolean {
  const values = Object.fromEntries(
    content
      .split(/\r?\n/)
      .filter((line) => line.includes('='))
      .map((line) => {
        const separator = line.indexOf('=')
        return [line.slice(0, separator), line.slice(separator + 1)]
      }),
  )
  return Boolean(
    !values.POSTGRES_PASSWORD ||
      !values.PAYLOAD_SECRET ||
      values.POSTGRES_PASSWORD.length < 32 ||
      values.PAYLOAD_SECRET.length < 48 ||
      isPlaceholder(values.POSTGRES_PASSWORD) ||
      isPlaceholder(values.PAYLOAD_SECRET) ||
      values.ENABLE_TEST_ROUTES === 'true',
  )
}

export function renderProductionConfig(
  input: ProductionInstallInput,
  secrets: { postgresPassword: string; payloadSecret: string },
): string {
  validateProductionInstallInput(input)
  if (secrets.postgresPassword.length < 32 || secrets.payloadSecret.length < 48)
    throw new ProductionInstallError(['generated secrets'])
  return [
    '# Renegade CMS production configuration (generated by install.sh)',
    'NODE_ENV=production',
    `POSTGRES_PASSWORD=${secrets.postgresPassword}`,
    `PAYLOAD_SECRET=${secrets.payloadSecret}`,
    `APP_URL=${input.appUrl}`,
    `PROXY_MODE=${input.proxyMode}`,
    `TRUSTED_PROXY_HOPS=${input.trustedProxyHops}`,
    `RENEGADE_WEB_BIND=${input.webBind}`,
    `DEPLOYMENT_PROFILE=${input.profile}`,
    'STORAGE_DRIVER=local',
    'MEDIA_DIR=/app/media',
    'EMAIL_MODE=disabled',
    'LOG_LEVEL=info',
    'ENABLE_TEST_ROUTES=false',
    ...(input.ownerEmail ? [`OWNER_EMAIL=${input.ownerEmail}`] : []),
    '',
  ].join('\n')
}

function isPlaceholder(value: string): boolean {
  return /replace|build-only|changeme|example|development-secret|dev_only/i.test(value)
}
