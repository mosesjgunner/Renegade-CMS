import { type MigrateDownArgs, type MigrateUpArgs, sql } from '@payloadcms/db-postgres'

/**
 * POD-08 (POD-REQ-13): server waveform peaks for media assets.
 *
 * media-assets gain `waveform_peaks` (jsonb) — the POD-08 peaks format
 * v1 ({ version, peaksPerSecond: 100, sampleRate: 48000, durationSec,
 * sourceChecksum, min[], max[] }) written by the `media-peaks` queue
 * task (src/modules/media/peaks.ts). The task slug is added to
 * Payload's `enum_payload_jobs_task_slug` and
 * `enum_payload_jobs_log_task_slug` (both enums bake registered task
 * slugs; queueing fails without them — the POD-02 lesson).
 *
 * Rollback note: `down` drops exactly the column `up` adds, discarding
 * stored peaks (they are a pure cache of the asset bytes and can be
 * regenerated by re-running the media-peaks task). The two task-slug
 * enum values cannot be removed by Postgres and stay, inert.
 */
export async function up({ db }: MigrateUpArgs): Promise<void> {
  await db.execute(sql`
    ALTER TABLE "media_assets"
      ADD COLUMN IF NOT EXISTS "waveform_peaks" jsonb;
    ALTER TYPE "public"."enum_payload_jobs_task_slug" ADD VALUE IF NOT EXISTS 'media-peaks';
    ALTER TYPE "public"."enum_payload_jobs_log_task_slug" ADD VALUE IF NOT EXISTS 'media-peaks';
  `)
}

export async function down({ db }: MigrateDownArgs): Promise<void> {
  await db.execute(sql`
    ALTER TABLE "media_assets"
      DROP COLUMN IF EXISTS "waveform_peaks";
  `)
}
