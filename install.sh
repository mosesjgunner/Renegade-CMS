#!/usr/bin/env bash
# Supported production bootstrap. It deliberately starts only PostgreSQL, web, and worker.
set -Eeuo pipefail

root="$(CDPATH= cd -- "$(dirname -- "$0")" && pwd)"
cd "$root"
config_file="$root/.env.production"
non_interactive=false
app_url="${APP_URL:-}"
proxy_mode="${PROXY_MODE:-trusted}"
proxy_hops="${TRUSTED_PROXY_HOPS:-1}"
profile="${DEPLOYMENT_PROFILE:-}"
web_bind="${RENEGADE_WEB_BIND:-127.0.0.1:3000}"
owner_email="${OWNER_EMAIL:-}"
instance="${RENEGADE_INSTANCE:-}"
instance_supplied=false
image_ref="${RENEGADE_IMAGE:-}"
image_supplied=false
prebuilt=false
network_subnet="${RENEGADE_NETWORK_SUBNET:-}"
network_subnet_supplied=false
existing_config=false

usage() {
  cat <<'EOF'
Usage: ./install.sh [--non-interactive] --instance <slug> --app-url https://cms.example.com [options]
  --instance <slug>              Docker Compose project identity (required for new installs)
  --image <ref>                  Use this prebuilt release image instead of building from
                                 source (advanced; pin a digest you have verified — release
                                 images are not signed)
  --proxy-mode trusted|direct     Default: trusted
  --trusted-proxy-hops 1|2|3     Default: 1
  --profile Lean|Standard         Default: selected from RAM
  --web-bind 127.0.0.1:3000      Loopback listener only
  --network-subnet 10.204.1.0/24  Optional private Compose subnet when Docker's pool is exhausted
  --owner-email owner@example.com Optional setup owner lock
EOF
}
fail() { echo "Install failed: $*" >&2; exit 1; }
ask() { local prompt="$1" value="$2"; read -r -p "$prompt [$value]: " answer; printf '%s' "${answer:-$value}"; }

# Docker's build context excludes .git. Bind the exported source to this checkout.
source_sha="$(git rev-parse HEAD 2>/dev/null || true)"
if [[ -z "$source_sha" ]]; then source_sha="${BUILD_SHA:-}"; fi
[[ "$source_sha" =~ ^[a-f0-9]{40}$ ]] || fail 'a Git checkout or an explicit full BUILD_SHA is required.'
export BUILD_SHA="$source_sha"

while (($#)); do
  case "$1" in
    --non-interactive) non_interactive=true ;;
    --app-url) app_url="${2:?missing value}"; shift ;;
    --proxy-mode) proxy_mode="${2:?missing value}"; shift ;;
    --trusted-proxy-hops) proxy_hops="${2:?missing value}"; shift ;;
    --profile) profile="${2:?missing value}"; shift ;;
    --web-bind) web_bind="${2:?missing value}"; shift ;;
    --owner-email) owner_email="${2:?missing value}"; shift ;;
    --instance) instance="${2:?missing value}"; instance_supplied=true; shift ;;
    --image) image_ref="${2:?missing value}"; image_supplied=true; shift ;;
    --network-subnet) network_subnet="${2:?missing value}"; network_subnet_supplied=true; shift ;;
    --help|-h) usage; exit 0 ;;
    *) fail "unknown argument: $1" ;;
  esac
  shift
done

command -v docker >/dev/null || fail 'Docker is required. Install Docker Engine, then rerun.'
docker info >/dev/null 2>&1 || fail 'Docker is installed but unavailable to this user.'
compose_version="$(docker compose version --short 2>/dev/null || true)"
[[ "$compose_version" =~ ^v?([2-9]|[1-9][0-9]+)\. ]] || fail 'Docker Compose v2 or newer is required.'
case "$(uname -m)" in x86_64|aarch64|arm64) ;; *) fail "unsupported CPU architecture: $(uname -m)" ;; esac
[[ -r /proc/meminfo ]] || fail 'cannot determine available RAM.'
ram_mb="$(( $(awk '/MemTotal/ { print $2; exit }' /proc/meminfo) / 1024 ))"
disk_mb="$(( $(df -Pk "$root" | awk 'NR==2 { print $4 }') / 1024 ))"
(( disk_mb >= 10240 )) || fail "at least 10 GB free disk is required (found ${disk_mb} MB)."

if [[ -z "$profile" ]]; then
  if (( ram_mb < 2048 )); then profile=Lean; else profile=Standard; fi
fi
[[ "$profile" == Lean || "$profile" == Standard ]] || fail 'profile must be Lean or Standard.'
(( ram_mb >= 1024 )) || fail "at least 1 GB RAM is required (found ${ram_mb} MB)."
[[ "$profile" != Standard || "$ram_mb" -ge 2048 ]] || fail 'Standard requires 2 GB RAM; choose Lean or add RAM.'
if [[ "$profile" == Lean ]] && (( ram_mb < 2048 )); then
  echo "Note: this host has ${ram_mb} MB RAM. Lean is supported from 1 GB (measured), but 2 GB is the recommended floor for any profile; expect tight headroom under load."
fi

if [[ -f "$config_file" ]]; then
  grep -qxF '# Renegade CMS production configuration (generated by install.sh)' "$config_file" || fail '.env.production already exists and was not created by this installer; refusing to overwrite it.'
  existing_config=true
  read_config() { sed -n "s/^$1=//p" "$config_file" | head -n 1; }
  app_url="$(read_config APP_URL)"
  proxy_mode="$(read_config PROXY_MODE)"
  proxy_hops="$(read_config TRUSTED_PROXY_HOPS)"
  profile="$(read_config DEPLOYMENT_PROFILE)"
  web_bind="$(read_config RENEGADE_WEB_BIND)"
  owner_email="$(read_config OWNER_EMAIL)"
  configured_instance="$(read_config RENEGADE_INSTANCE)"
  configured_network_subnet="$(read_config RENEGADE_NETWORK_SUBNET)"
  # Older installer-managed environments used the fixed renegade-cms project.
  # Keep that identity so their existing named volumes remain attached.
  configured_instance="${configured_instance:-renegade-cms}"
  if $instance_supplied && [[ "$instance" != "$configured_instance" ]]; then
    fail "--instance '$instance' does not match this installation's persisted instance '$configured_instance'."
  fi
  instance="$configured_instance"
  if [[ -n "$configured_network_subnet" ]]; then
    if $network_subnet_supplied && [[ "$network_subnet" != "$configured_network_subnet" ]]; then
      fail '--network-subnet does not match the persisted installation subnet.'
    fi
    network_subnet="$configured_network_subnet"
  fi
fi

if ! $existing_config && [[ -z "$instance" ]]; then
  fail '--instance is required for a new installation.'
fi
[[ "$instance" =~ ^[a-z0-9][a-z0-9_-]{0,62}$ ]] || fail 'instance must be 1-63 lowercase letters, digits, hyphens, or underscores and start with a letter or digit.'
# Fresh installs use a project-specific image name, so building one installation
# cannot replace the tag another installation will use on its next restart.
# An operator-supplied --image switches to the prebuilt path instead: the image
# is pulled, never built, and must be the artifact built from this checkout's
# BUILD_SHA (release images are tagged by source SHA; they are not signed, so
# pin a digest you have verified out of band).
if $existing_config && $image_supplied; then
  fail '--image cannot change an existing installation. Its image is recorded in .env.production.'
fi
if ! $existing_config; then
  if $image_supplied; then
    export RENEGADE_IMAGE="$image_ref"
    prebuilt=true
  else
    export RENEGADE_IMAGE="renegade-cms-$instance"
  fi
fi
compose=(docker compose --project-name "$instance" --env-file "$config_file" -f compose.production.yaml)
if [[ -n "$network_subnet" ]]; then
  [[ "$network_subnet" =~ ^([0-9]{1,3}\.){3}[0-9]{1,3}/([0-9]{1,2})$ ]] || fail 'RENEGADE_NETWORK_SUBNET must be an IPv4 CIDR.'
  IFS=./ read -r octet1 octet2 octet3 octet4 prefix <<< "$network_subnet"
  for octet in "$octet1" "$octet2" "$octet3" "$octet4"; do
    (( 10#$octet <= 255 )) || fail 'RENEGADE_NETWORK_SUBNET has an invalid IPv4 octet.'
  done
  (( 10#$prefix >= 16 && 10#$prefix <= 30 )) || fail 'RENEGADE_NETWORK_SUBNET prefix must be between 16 and 30.'
  export RENEGADE_NETWORK_SUBNET="$network_subnet"
  compose+=(-f compose.network.yaml)
fi

if ! $non_interactive && ! $existing_config; then
  app_url="$(ask 'Public HTTPS URL' "${app_url:-https://cms.example.com}")"
  profile="$(ask 'Deployment profile (Lean or Standard)' "$profile")"
  owner_email="$(ask 'Optional owner email (blank is allowed)' "$owner_email")"
fi
[[ "$profile" == Lean || "$profile" == Standard ]] || fail 'profile must be Lean or Standard.'
[[ -n "$app_url" ]] || fail '--app-url is required in non-interactive mode.'
[[ "$app_url" =~ ^https://[^/?#]+/?$ && "$app_url" != *localhost* && "$app_url" != *127.0.0.1* ]] || fail 'APP_URL must be a non-loopback HTTPS origin with no path.'
[[ "$app_url" != *@* ]] || fail 'APP_URL must not contain credentials.'
[[ "$proxy_mode" == trusted || "$proxy_mode" == direct ]] || fail 'PROXY_MODE must be trusted or direct.'
[[ "$proxy_hops" =~ ^[1-3]$ ]] || fail 'TRUSTED_PROXY_HOPS must be 1, 2, or 3.'
[[ "$web_bind" =~ ^127\.0\.0\.1:[0-9]{1,5}$ || "$web_bind" =~ ^\[::1\]:[0-9]{1,5}$ ]] || fail 'RENEGADE_WEB_BIND must be a loopback host and port.'
[[ -z "$owner_email" || "$owner_email" =~ ^[^[:space:]@]+@[^[:space:]@]+\.[^[:space:]@]+$ ]] || fail 'OWNER_EMAIL is malformed.'

port="${web_bind##*:}"
(( 10#$port >= 1 && 10#$port <= 65535 )) || fail 'RENEGADE_WEB_BIND port must be between 1 and 65535.'
if command -v ss >/dev/null && ss -ltn "sport = :$port" | grep -q LISTEN; then
  # A rerun against this installation's own running deployment is the
  # documented recovery path, and its web container legitimately holds the
  # port. Only fail when the listener is not ours.
  own_listener=false
  if $existing_config; then
    web_container="$("${compose[@]}" ps -q renegade-web 2>/dev/null | head -n 1 || true)"
    if [[ -n "$web_container" ]]; then
      published="$(docker port "$web_container" 3000/tcp 2>/dev/null || true)"
      if [[ "$published" == *":$port" ]]; then own_listener=true; fi
    fi
  fi
  if $own_listener; then
    echo "Port $port is held by this installation's running web service; continuing so Compose can reconcile it."
  else
    fail "port $port is already in use by another process. Stop that process or choose a different --web-bind port."
  fi
fi
probe="$root/.renegade-install-write-probe-$$"
touch "$probe" && rm -f "$probe" || fail 'installation directory is not writable.'

if [[ -f "$config_file" ]]; then
  grep -qxF '# Renegade CMS production configuration (generated by install.sh)' "$config_file" || fail '.env.production already exists and was not created by this installer; refusing to overwrite it.'
  existing_postgres_password="$(read_config POSTGRES_PASSWORD)"
  existing_payload_secret="$(read_config PAYLOAD_SECRET)"
  [[ ${#existing_postgres_password} -ge 32 ]] || fail 'existing production configuration has an unsafe database password.'
  [[ ${#existing_payload_secret} -ge 48 ]] || fail 'existing production configuration has an unsafe Payload secret.'
  unset existing_postgres_password existing_payload_secret
  grep -Eq 'POSTGRES_PASSWORD=(replace|build-only|changeme|example|development-secret|dev_only)' "$config_file" && fail 'existing production configuration has a placeholder database password.'
  grep -Eq 'PAYLOAD_SECRET=(replace|build-only|changeme|example|development-secret|dev_only)' "$config_file" && fail 'existing production configuration has a placeholder Payload secret.'
  grep -qxF 'ENABLE_TEST_ROUTES=true' "$config_file" && fail 'existing production configuration enables test routes.'
  echo 'Restarting the existing installer-managed deployment; configuration is unchanged.'
else
  secret() { openssl rand -base64 "$1" | tr -d '\n' | tr '/+' '_-'; }
  command -v openssl >/dev/null || fail 'openssl is required to generate production secrets.'
  postgres_password="$(secret 36)"
  payload_secret="$(secret 54)"
  umask 077
  tmp_config="$config_file.tmp.$$"
  {
    echo '# Renegade CMS production configuration (generated by install.sh)'
    echo 'NODE_ENV=production'
    echo "POSTGRES_PASSWORD=$postgres_password"
    echo "PAYLOAD_SECRET=$payload_secret"
    echo "APP_URL=${app_url%/}"
    echo "PROXY_MODE=$proxy_mode"
    echo "TRUSTED_PROXY_HOPS=$proxy_hops"
    echo "RENEGADE_WEB_BIND=$web_bind"
    echo "RENEGADE_INSTANCE=$instance"
    echo "RENEGADE_IMAGE=$RENEGADE_IMAGE"
    [[ -z "$network_subnet" ]] || echo "RENEGADE_NETWORK_SUBNET=$network_subnet"
    echo "DEPLOYMENT_PROFILE=$profile"
    echo "BUILD_SHA=$BUILD_SHA"
    echo 'STORAGE_DRIVER=local'; echo 'MEDIA_DIR=/app/media'; echo 'EMAIL_MODE=disabled'
    echo 'LOG_LEVEL=info'; echo 'ENABLE_TEST_ROUTES=false'
    [[ -z "$owner_email" ]] || echo "OWNER_EMAIL=$owner_email"
  } > "$tmp_config"
  mv "$tmp_config" "$config_file"
  unset postgres_password payload_secret
  echo 'Generated .env.production with new secrets (values are not printed).'
fi

if $existing_config && $network_subnet_supplied && [[ -z "$configured_network_subnet" ]]; then
  # This is installer-owned configuration. Persist the explicit network choice
  # so subsequent restarts use the same network without changing data volumes.
  printf 'RENEGADE_NETWORK_SUBNET=%s\n' "$network_subnet" >> "$config_file"
fi

# --- Bundled audio engine (ffmpeg) -------------------------------------
# Podcast recording, rendering and live streaming need ffmpeg. The
# installer bundles a pinned build (scripts/ffmpeg-bundle.json) into
# vendor/ffmpeg/, which compose.production.yaml mounts read-only into the
# app containers.
#
# Failure policy — two different cases, kept distinct on purpose:
#   * Tampering: a download was attempted and its SHA-256 did NOT match
#     the pin. That fails closed: the whole install stops and no
#     unverified binary is ever used.
#   * Unavailability: no way to run the installer script, or the download
#     simply could not be reached. That warns and continues — the engine
#     is optional at install time and an owner can install it later from
#     the Capability Center.
#
# One implementation only: scripts/install-bundled-ffmpeg.mjs. Host node
# is preferred when present. Docker is already required by this script,
# so without host node we run the same script in a node container: the
# checkout is mounted at /bundle and the script resolves the repo root
# from its own path, so inside the container its root is /bundle and its
# default target (/bundle/vendor/ffmpeg) is this checkout's
# vendor/ffmpeg on the host — no --dir override is needed.
if [[ -x "$root/vendor/ffmpeg/ffmpeg" ]] && "$root/vendor/ffmpeg/ffmpeg" -version >/dev/null 2>&1; then
  echo 'Audio engine: bundled ffmpeg is already present.'
else
  echo 'Audio engine: installing the bundled ffmpeg…'
  audio_engine_output=''
  audio_engine_status=0
  if command -v node >/dev/null 2>&1; then
    audio_engine_output="$(node "$root/scripts/install-bundled-ffmpeg.mjs" 2>&1)" || audio_engine_status=$?
  else
    audio_engine_output="$(docker run --rm -v "$root:/bundle" -w /bundle node:24-alpine node scripts/install-bundled-ffmpeg.mjs 2>&1)" || audio_engine_status=$?
  fi
  [[ -z "$audio_engine_output" ]] || printf '%s\n' "$audio_engine_output"
  if [[ $audio_engine_status -ne 0 ]]; then
    if [[ "$audio_engine_output" == *FFMPEG_BUNDLE_CHECKSUM_MISMATCH* ]]; then
      fail 'the audio engine download did not match its pinned checksum; refusing to continue with an unverified binary.'
    fi
    echo 'Warning: the audio engine could not be installed now. Podcast recording, rendering and live streaming will stay off until it is installed; an owner can install it later from the Capability Center.' >&2
  fi
  unset audio_engine_output audio_engine_status
fi

"${compose[@]}" config --quiet || fail 'production compose configuration is invalid.'
echo "Preflight passed: ${ram_mb} MB RAM, ${disk_mb} MB disk, ${profile} profile. Starting PostgreSQL, migrations, web, and worker..."
if $prebuilt; then
  "${compose[@]}" pull || fail "could not pull the prebuilt image '$RENEGADE_IMAGE'. Verify the reference and registry access, then rerun ./install.sh."
  "${compose[@]}" up -d --wait || fail 'containers did not become healthy. Fix the reported issue and rerun ./install.sh; configuration and volumes were preserved.'
else
  "${compose[@]}" up --build -d --wait || fail 'containers did not become healthy. Fix the reported issue and rerun ./install.sh; configuration and volumes were preserved.'
fi
"${compose[@]}" exec -T renegade-web node -e "fetch('http://127.0.0.1:3000/health/ready').then(r=>process.exit(r.ok?0:1)).catch(()=>process.exit(1))" || fail 'web readiness check failed.'
"${compose[@]}" exec -T renegade-worker node docker/worker-healthcheck.mjs || fail 'worker heartbeat check failed.'

echo
echo 'Renegade CMS is ready.'
echo "Setup URL: ${app_url%/}/setup"
# UXI-04: the primary claim handoff is a fragment link. The web container
# announces the one-time token (and the ready-made claim link) in its log
# on first start; the installer reads that line locally and prints the
# claim link here, in the operator's own terminal. The token rides in the
# URL fragment (#claim=...), which browsers never send to the server, so
# opening the link puts the token in no access log or referrer. If the
# token cannot be read here (log already rotated, container restarted),
# fall back to retrieving it locally — never paste it into tickets/chat.
claim_token=''
claim_log_line="$("${compose[@]}" logs renegade-web 2>/dev/null | grep 'setup token' | tail -n 1 || true)"
if [[ "$claim_log_line" == *': '* ]]; then
  claim_token="${claim_log_line##*: }"
fi
if [[ "$claim_token" =~ ^[A-Za-z0-9_-]{43}$ ]]; then
  echo 'Claim your installation (primary handoff; valid 15 minutes, single use):'
  echo "  ${app_url%/}/setup#claim=$claim_token"
  echo 'Open that link in your browser: the token is read from the link fragment and removed from the address bar immediately.'
  echo 'Fallback (only if the link does not work): retrieve the one-time token locally with:'
  echo "  docker compose --project-name $instance --env-file .env.production -f compose.production.yaml logs renegade-web | grep 'setup token'"
else
  echo 'Retrieve the one-time bootstrap token (valid 15 minutes) locally with:'
  echo "  docker compose --project-name $instance --env-file .env.production -f compose.production.yaml logs renegade-web | grep 'setup token'"
  echo "Then open ${app_url%/}/setup#claim=<token> with the token in place of <token>, or paste the token into the setup form."
fi
unset claim_token claim_log_line
echo 'Use a reverse proxy (Caddy, Nginx, Traefik, or equivalent) for TLS and forward it only to the loopback listener. In trusted mode it must overwrite forwarded headers. See docs/operations/reverse-proxy.md for the managed Caddy path and the existing-proxy variant.'
