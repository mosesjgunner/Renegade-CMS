#!/usr/bin/env bash
# Supported production bootstrap. It deliberately starts only PostgreSQL, web, and worker.
set -Eeuo pipefail

root="$(CDPATH= cd -- "$(dirname -- "$0")" && pwd)"
cd "$root"
config_file="$root/.env.production"
compose=(docker compose --env-file "$config_file" -f compose.production.yaml)
non_interactive=false
app_url="${APP_URL:-}"
proxy_mode="${PROXY_MODE:-trusted}"
proxy_hops="${TRUSTED_PROXY_HOPS:-1}"
profile="${DEPLOYMENT_PROFILE:-}"
web_bind="${RENEGADE_WEB_BIND:-127.0.0.1:3000}"
owner_email="${OWNER_EMAIL:-}"

usage() {
  cat <<'EOF'
Usage: ./install.sh [--non-interactive] --app-url https://cms.example.com [options]
  --proxy-mode trusted|direct     Default: trusted
  --trusted-proxy-hops 1|2|3     Default: 1
  --profile Lean|Standard         Default: selected from RAM
  --web-bind 127.0.0.1:3000      Loopback listener only
  --owner-email owner@example.com Optional setup owner lock
EOF
}
fail() { echo "Install failed: $*" >&2; exit 1; }
ask() { local prompt="$1" value="$2"; read -r -p "$prompt [$value]: " answer; printf '%s' "${answer:-$value}"; }

while (($#)); do
  case "$1" in
    --non-interactive) non_interactive=true ;;
    --app-url) app_url="${2:?missing value}"; shift ;;
    --proxy-mode) proxy_mode="${2:?missing value}"; shift ;;
    --trusted-proxy-hops) proxy_hops="${2:?missing value}"; shift ;;
    --profile) profile="${2:?missing value}"; shift ;;
    --web-bind) web_bind="${2:?missing value}"; shift ;;
    --owner-email) owner_email="${2:?missing value}"; shift ;;
    --help|-h) usage; exit 0 ;;
    *) fail "unknown argument: $1" ;;
  esac
  shift
done

command -v docker >/dev/null || fail 'Docker is required. Install Docker Engine, then rerun.'
docker info >/dev/null 2>&1 || fail 'Docker is installed but unavailable to this user.'
compose_version="$(docker compose version --short 2>/dev/null || true)"
[[ "$compose_version" =~ ^v?([2-9]|[1-9][0-9]+)\. ]] || fail 'Docker Compose v2 or newer is required.'
case "$(uname -m)" in x86_64|aarch64|arm64) ;; *) fail "unsupported CPU architecture: $(uname -m)" ;; esac
[[ -r /proc/meminfo ]] || fail 'cannot determine available RAM.'
ram_mb="$(( $(awk '/MemTotal/ { print $2; exit }' /proc/meminfo) / 1024 ))"
disk_mb="$(( $(df -Pk "$root" | awk 'NR==2 { print $4 }') / 1024 ))"
(( disk_mb >= 10240 )) || fail "at least 10 GB free disk is required (found ${disk_mb} MB)."

if [[ -z "$profile" ]]; then
  if (( ram_mb < 2048 )); then profile=Lean; else profile=Standard; fi
fi
[[ "$profile" == Lean || "$profile" == Standard ]] || fail 'profile must be Lean or Standard.'
(( ram_mb >= 1024 )) || fail "at least 1 GB RAM is required (found ${ram_mb} MB)."
[[ "$profile" != Standard || "$ram_mb" -ge 2048 ]] || fail 'Standard requires 2 GB RAM; choose Lean or add RAM.'

if [[ -f "$config_file" ]]; then
  grep -qxF '# Renegade CMS production configuration (generated by install.sh)' "$config_file" || fail '.env.production already exists and was not created by this installer; refusing to overwrite it.'
  existing_config=true
  read_config() { sed -n "s/^$1=//p" "$config_file" | head -n 1; }
  app_url="$(read_config APP_URL)"
  proxy_mode="$(read_config PROXY_MODE)"
  proxy_hops="$(read_config TRUSTED_PROXY_HOPS)"
  profile="$(read_config DEPLOYMENT_PROFILE)"
  web_bind="$(read_config RENEGADE_WEB_BIND)"
  owner_email="$(read_config OWNER_EMAIL)"
fi

if ! $non_interactive && ! $existing_config; then
  app_url="$(ask 'Public HTTPS URL' "${app_url:-https://cms.example.com}")"
  profile="$(ask 'Deployment profile (Lean or Standard)' "$profile")"
  owner_email="$(ask 'Optional owner email (blank is allowed)' "$owner_email")"
fi
[[ "$profile" == Lean || "$profile" == Standard ]] || fail 'profile must be Lean or Standard.'
[[ -n "$app_url" ]] || fail '--app-url is required in non-interactive mode.'
[[ "$app_url" =~ ^https://[^/?#]+/?$ && "$app_url" != *localhost* && "$app_url" != *127.0.0.1* ]] || fail 'APP_URL must be a non-loopback HTTPS origin with no path.'
[[ "$proxy_mode" == trusted || "$proxy_mode" == direct ]] || fail 'PROXY_MODE must be trusted or direct.'
[[ "$proxy_hops" =~ ^[1-3]$ ]] || fail 'TRUSTED_PROXY_HOPS must be 1, 2, or 3.'
[[ "$web_bind" =~ ^127\.0\.0\.1:[0-9]{1,5}$ || "$web_bind" =~ ^\[::1\]:[0-9]{1,5}$ ]] || fail 'RENEGADE_WEB_BIND must be a loopback host and port.'
[[ -z "$owner_email" || "$owner_email" =~ ^[^[:space:]@]+@[^[:space:]@]+\.[^[:space:]@]+$ ]] || fail 'OWNER_EMAIL is malformed.'

port="${web_bind##*:}"
if command -v ss >/dev/null && ss -ltn "sport = :$port" | grep -q LISTEN; then fail "port $port is already in use."; fi
probe="$root/.renegade-install-write-probe-$$"
touch "$probe" && rm -f "$probe" || fail 'installation directory is not writable.'

if [[ -f "$config_file" ]]; then
  grep -qxF '# Renegade CMS production configuration (generated by install.sh)' "$config_file" || fail '.env.production already exists and was not created by this installer; refusing to overwrite it.'
  existing_postgres_password="$(read_config POSTGRES_PASSWORD)"
  existing_payload_secret="$(read_config PAYLOAD_SECRET)"
  [[ ${#existing_postgres_password} -ge 32 ]] || fail 'existing production configuration has an unsafe database password.'
  [[ ${#existing_payload_secret} -ge 48 ]] || fail 'existing production configuration has an unsafe Payload secret.'
  unset existing_postgres_password existing_payload_secret
  grep -Eq 'POSTGRES_PASSWORD=(replace|build-only|changeme|example|development-secret|dev_only)' "$config_file" && fail 'existing production configuration has a placeholder database password.'
  grep -Eq 'PAYLOAD_SECRET=(replace|build-only|changeme|example|development-secret|dev_only)' "$config_file" && fail 'existing production configuration has a placeholder Payload secret.'
  grep -qxF 'ENABLE_TEST_ROUTES=true' "$config_file" && fail 'existing production configuration enables test routes.'
  echo 'Restarting the existing installer-managed deployment; configuration is unchanged.'
else
  secret() { openssl rand -base64 "$1" | tr -d '\n' | tr '/+' '_-'; }
  command -v openssl >/dev/null || fail 'openssl is required to generate production secrets.'
  postgres_password="$(secret 36)"
  payload_secret="$(secret 54)"
  umask 077
  tmp_config="$config_file.tmp.$$"
  {
    echo '# Renegade CMS production configuration (generated by install.sh)'
    echo 'NODE_ENV=production'
    echo "POSTGRES_PASSWORD=$postgres_password"
    echo "PAYLOAD_SECRET=$payload_secret"
    echo "APP_URL=${app_url%/}"
    echo "PROXY_MODE=$proxy_mode"
    echo "TRUSTED_PROXY_HOPS=$proxy_hops"
    echo "RENEGADE_WEB_BIND=$web_bind"
    echo "DEPLOYMENT_PROFILE=$profile"
    echo 'STORAGE_DRIVER=local'; echo 'MEDIA_DIR=/app/media'; echo 'EMAIL_MODE=disabled'
    echo 'LOG_LEVEL=info'; echo 'ENABLE_TEST_ROUTES=false'
    [[ -z "$owner_email" ]] || echo "OWNER_EMAIL=$owner_email"
  } > "$tmp_config"
  mv "$tmp_config" "$config_file"
  unset postgres_password payload_secret
  echo 'Generated .env.production with new secrets (values are not printed).'
fi

"${compose[@]}" config --quiet || fail 'production compose configuration is invalid.'
echo "Preflight passed: ${ram_mb} MB RAM, ${disk_mb} MB disk, ${profile} profile. Starting PostgreSQL, migrations, web, and worker..."
"${compose[@]}" up --build -d --wait || fail 'containers did not become healthy. Fix the reported issue and rerun ./install.sh; configuration and volumes were preserved.'
"${compose[@]}" exec -T renegade-web node -e "fetch('http://127.0.0.1:3000/health/ready').then(r=>process.exit(r.ok?0:1)).catch(()=>process.exit(1))" || fail 'web readiness check failed.'
"${compose[@]}" exec -T renegade-worker node docker/worker-healthcheck.mjs || fail 'worker heartbeat check failed.'

echo
echo 'Renegade CMS is ready.'
echo "Setup URL: ${app_url%/}/setup"
echo 'Open the setup URL, then retrieve the one-time bootstrap token locally with:'
echo '  docker compose --env-file .env.production -f compose.production.yaml logs renegade-web'
echo 'Use a reverse proxy (Caddy, Nginx, Traefik, or equivalent) for TLS and forward it only to the loopback listener. In trusted mode it must overwrite forwarded headers.'
